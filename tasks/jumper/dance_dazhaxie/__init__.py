"""jumper.dance_dazhaxie -- the hairy-crab dance (大闸蟹舞), authored for the 2026
crab-robot open-source motion challenge, learned by imitation.

The same task as `jumper.dance` with a different clip: the environment is
`tasks/jumper/common/dance/env.py`, and what this directory adds is the clip and
the numbers.

## The clip

`media/dazhaxie.npz` is **authored, not recorded**: it is generated by
`tools/author_dazhaxie_dance.py` from a pose library and a beat timeline, at
120 BPM, 50 Hz, in the schema `common/dance/motion.py` reads. Every pose in the
library was found by forward-kinematics search on this robot's own model
(`_scratch` pose search, kept in the submission repository), so the arm targets
are reachable and expressive rather than guessed joint by joint.

The choreography keeps the four support feet planted at the standing pose and
dances with the body pose and the two 5-DoF front arms -- the claws. That is a
design decision and not a limitation discovered later: a support foot lifted for
a beat is a foot the imitation reward scores as an error for the frames it is in
the air, and the pose check in `motion.py` judges a clip's median frame, so a
choreography that spends beats on three feet is fine there and bad training here.

The music is not committed (the piece is authored to a 120 BPM grid, so any
track at that tempo fits); training never reads it. The performance video
`scripts/export.py` renders needs it, so export with `--no-video` or place a
track in `media/`.
"""

